import Foundation
@main
struct MacPolicyTests {
    static func main() throws {
        let app = ProtectedApp(bundleID: "test.editor", name: "Editor", path: "/Applications/Editor.app")
        let other = ProtectedApp(bundleID: "test.chat", name: "Chat", path: "/Applications/Chat.app")
        var policy = LockPolicy()
        policy.protect(app)
        precondition(!policy.isUnlocked(app.bundleID, pid: 10))
        precondition(policy.unlock(app.bundleID, pid: 10, ticket: policy.ticket(for: app.bundleID)))
        precondition(policy.isUnlocked(app.bundleID, pid: 10))
        precondition(!policy.isUnlocked(app.bundleID, pid: 11), "A restarted or second process must not inherit a grant")
        let beforeFocusLoss = policy.ticket(for: app.bundleID)
        policy.lock(app.bundleID)
        precondition(!policy.isUnlocked(app.bundleID, pid: 10))
        precondition(!policy.unlock(app.bundleID, pid: 10, ticket: beforeFocusLoss))
        let beforeLockAll = policy.ticket(for: app.bundleID)
        policy.lockAll()
        precondition(!policy.unlock(app.bundleID, pid: 10, ticket: beforeLockAll))
        let beforeCancel = policy.ticket(for: app.bundleID)
        policy.invalidateAuthentication()
        precondition(!policy.unlock(app.bundleID, pid: 10, ticket: beforeCancel))
        precondition(!policy.unlock(app.bundleID, pid: 10, ticket: policy.ticket(for: other.bundleID)))
        precondition(!policy.unlock(other.bundleID, pid: 20, ticket: policy.ticket(for: other.bundleID)))
        policy.protect(app)
        precondition(policy.apps.count == 1 && !policy.isUnlocked(app.bundleID, pid: 10))
        let beforeNewProtection = policy.ticket(for: app.bundleID)
        policy.protect(other)
        precondition(!policy.unlock(app.bundleID, pid: 10, ticket: beforeNewProtection))
        precondition(policy.unlock(app.bundleID, pid: 10, ticket: policy.ticket(for: app.bundleID)))
        let reloaded = LockPolicy(apps: try JSONDecoder().decode([ProtectedApp].self, from: JSONEncoder().encode(policy.apps)))
        precondition(!reloaded.isUnlocked(app.bundleID, pid: 10), "Disk persistence must never contain grants")
        let staleRemoval = policy.ticket(for: app.bundleID)
        policy.lockAll()
        precondition(!policy.remove(app.bundleID, ticket: staleRemoval))
        precondition(policy.app(app.bundleID) != nil)
        precondition(policy.remove(app.bundleID, ticket: policy.ticket(for: app.bundleID)))
        precondition(policy.app(app.bundleID) == nil)
        let quitTicket = policy.ticket()
        policy.invalidateAuthentication()
        precondition(!policy.accepts(quitTicket))
        var tracker = MinimizeTracker()
        precondition(!tracker.update([1: false, 2: true]))
        precondition(!tracker.update([1: false, 2: true]))
        precondition(tracker.update([1: true, 2: true]), "Minimizing any app window should relock")
        precondition(!tracker.update([1: true, 2: true]), "An already minimized window must not repeatedly relock")
        precondition(!tracker.update([1: false]))
        precondition(tracker.update([1: true]))
        print("Mac lock policy passed: process scoping, focus/minimize relock, stale responses, removal, persistence, and quit invalidation.")
    }
}
